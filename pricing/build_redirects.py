#!/usr/bin/env python3
"""
Scissors by Sandy — own-domain booking links.

Writes site/_redirects, which Netlify reads after the build. It gives the shop a
booking URL on its OWN domain for every service:

    https://scissorsbysandy.com/book              -> the booking provider's profile
    https://scissorsbysandy.com/book/executive    -> that provider's page for The Executive

WHY THIS EXISTS
The booking link is currently baked into things nobody can edit later: the QR code on
the printed sign and the business cards, the Book button on Google Business Profile,
Apple Business Connect, Yelp, Instagram. Pointed at booksy.com, changing provider means
reprinting physical material and editing six platforms by hand.

Pointed at scissorsbysandy.com/book, changing provider is one edit in prices.json.
Nothing gets reprinted and no listing has to be touched.

Destinations come from prices.json, so they can never drift from the prices and the
buttons on the site, which are built from the same file.

302, NOT 301
These are deliberately temporary redirects. A 301 is cached by the browser more or less
forever: a client who taps the QR code today would keep landing on the OLD provider
after a switch, with no way to clear it from our side. 302 is re-checked every time, so
the day the destination changes, every client follows it.

Run automatically by the Netlify build, or on its own:  python3 build_redirects.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(HERE, '..', 'site')
D = json.load(open(os.path.join(HERE, 'prices.json')))

# The active booking provider. When the shop moves to Square, this block is what changes:
# a new profile URL, a new per-service URL pattern, and the per-service reference on each
# service in prices.json. Nothing else in the repo needs to know which provider is live.
PROFILE = D['booksy']['profile_url']
SERVICE_BASE = D['booksy']['widget_base']          # raw '&', not the HTML-escaped form
SERVICE_REF = 'variantId'                           # field on each service in prices.json


def rows():
    """(path, destination) for the general link and every service, in catalog order."""
    out = [('/book', PROFILE)]
    for cat in D['categories']:
        for s in cat['services']:
            ref = s.get(SERVICE_REF)
            if not ref:
                raise SystemExit(f"build_redirects: {s['name']} has no {SERVICE_REF}")
            out.append((f"/book/{s['id']}", f"{SERVICE_BASE}{ref}"))
    return out


def build():
    r = rows()
    paths = [p for p, _ in r]
    if len(set(paths)) != len(paths):
        raise SystemExit('build_redirects: duplicate booking path')

    width = max(len(p) for p in paths)
    lines = [
        '# Generated by pricing/build_redirects.py — do not edit by hand.',
        '# Booking links on the shop\'s own domain. 302 so the destination stays changeable;',
        '# a 301 would be cached in clients\' browsers and survive a provider switch.',
        '',
    ]
    lines += [f"{p.ljust(width)}  {dest}  302" for p, dest in r]
    lines.append('')

    out = os.path.join(SITE, '_redirects')
    open(out, 'w', encoding='utf-8').write('\n'.join(lines))
    return out, len(r)


if __name__ == '__main__':
    path, n = build()
    print(f"wrote site/_redirects — {n} booking paths")
